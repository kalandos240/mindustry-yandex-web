#!/usr/bin/env python3
"""Generate explicit JSON fields from the pinned original filter declarations."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "work/Mindustry/core/src/mindustry/maps/filters"
DEST = ROOT / "web-runtime/src/main/java/mindustry/web/BrowserMapFilterJson.java"
schemas = {}
for path in sorted(SOURCE.glob("*Filter.java")):
    if path.stem == "GenerateFilter":
        continue
    if not re.search(r"public class "+path.stem+r" extends GenerateFilter", path.read_text()):
        raise SystemExit("Pinned filter inheritance changed: " + path.stem)
    fields = []
    for line in path.read_text().splitlines():
        match = re.fullmatch(r"    public (float|int|boolean|String|Block|Seq<ItemStack>) ([^;]+);", line)
        if not match:
            if re.match(r"    public (?!static).*;", line) and "(" not in line.split("=")[0]:
                raise SystemExit("Unsupported pinned JSON field: " + line)
            continue
        kind, declarations = match.groups()
        for declaration in declarations.split(","):
            name = declaration.split("=")[0].strip()
            if not re.fullmatch(r"\w+", name):
                raise SystemExit(f"Unsupported pinned field declaration: {line}")
            fields.append((name, kind))
    schemas[path.stem] = fields
if len(schemas) != 16:
    raise SystemExit("Pinned original map filter registry changed")

out = '''package mindustry.web;

import arc.func.*;
import arc.struct.*;
import arc.util.serialization.*;
import arc.util.serialization.Json.*;
import mindustry.io.*;
import mindustry.maps.filters.*;
import mindustry.type.*;
import mindustry.world.*;

// Generated by scripts/generate-map-filter-codec.py from pinned v159.7 fields.
// TeaVM does not retain all of Arc Json's reflective field tables.
final class BrowserMapFilterJson{
    static <T extends GenerateFilter> void install(Class<T> type, Prov<T> factory){
        JsonIO.json.setSerializer(type, new Serializer<T>(){
            public void write(Json json, T value, Class knownType){
                json.writeObjectStart(type, knownType);
                writeFields(json, value);
                json.writeObjectEnd();
            }
            public T read(Json json, JsonValue data, Class requestedType){
                T value = factory.get();
                readFields(json, data, value);
                return value;
            }
        });
    }

    private static void writeFields(Json json, GenerateFilter value){
        json.writeValue("seed", value.seed);
'''
for name, fields in schemas.items():
    out += f"        if(value instanceof {name} f){{\n"
    for field, kind in fields:
        extra = ", Block.class" if kind == "Block" else ", Seq.class, ItemStack.class" if kind == "Seq<ItemStack>" else ""
        out += f'            json.writeValue("{field}", f.{field}{extra});\n'
    out += "            return;\n        }\n"
out += '''        throw new IllegalArgumentException("Unsupported original map filter: " + value.getClass().getName());
    }

    private static void readFields(Json json, JsonValue data, GenerateFilter value){
        value.seed = data.getInt("seed", value.seed);
'''
for name, fields in schemas.items():
    out += f"        if(value instanceof {name} f){{\n"
    for field, kind in fields:
        if kind in {"int", "float", "boolean", "String"}:
            method = {"int": "getInt", "float": "getFloat", "boolean": "getBoolean", "String": "getString"}[kind]
            expression = f'data.{method}("{field}", f.{field})'
        else:
            args = "Block.class" if kind == "Block" else "Seq.class, ItemStack.class"
            expression = f'json.readValue("{field}", {args}, f.{field}, data)'
        out += f"            f.{field} = {expression};\n"
    out += "            return;\n        }\n"
out += '''        throw new IllegalArgumentException("Unsupported original map filter: " + value.getClass().getName());
    }
}
'''
if "--check" in sys.argv:
    if not DEST.exists() or DEST.read_text() != out:
        raise SystemExit("Generated browser map-filter fields differ from pinned original declarations")
else:
    DEST.write_text(out)
print(f"Original filter JSON schema: {len(schemas)} types, {sum(len(v) for v in schemas.values())} declared fields + inherited seed")
